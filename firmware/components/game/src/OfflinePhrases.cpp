const char* offlinePhrase(CharacterId id, PhraseContext context, std::uint32_t salt, Lang lang)
{
    const auto charIndex = static_cast<unsigned>(id);
    const auto ctxIndex = static_cast<unsigned>(context);
    if (charIndex >= kCharacterCount || ctxIndex >= kContexts) {
        return "...";
    }
    if (lang == Lang::Ru) {
        return kPhrasesRu[charIndex][ctxIndex][salt % kVariants];
    }
    return kPhrases[charIndex][ctxIndex][salt % kVariants];
}


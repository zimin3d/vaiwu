#!/usr/bin/env python3
"""Build the static art gallery site into site/ (index.html + arts/).

Publishes the sprites, monsters and backdrops from assets/ as a small dark
themed gallery. Re-run after tools/gen_sprites.py to refresh the site.

Run from the project root:  python3 tools/gen_site.py
Deploy: copy site/ to the web root (see /etc/nginx/sites-available/vaiwu).
"""
import html
import os
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "assets")
OUT = os.path.join(ROOT, "site")

CHAR_TITLES = {
    "aoi": "Aoi", "hina": "Hina", "rin": "Rin", "yuki": "Yuki",
    "akane": "Akane", "unicorn": "Unicorn", "kolobok": "Kolobok",
}
EMOTIONS = ["idle", "happy", "sad", "angry", "sleepy", "sick", "dead"]
MONSTERS = ["slime", "bat", "shroom", "fox", "ghost", "golem"]
BG_PHASES = ["morning", "day", "evening", "night"]

CSS = """
:root { color-scheme: dark; }
* { box-sizing: border-box; }
body {
  margin: 0; padding: 2rem clamp(1rem, 5vw, 4rem);
  background: #18122b; color: #e8e2f4;
  font: 16px/1.5 system-ui, "Segoe UI", sans-serif;
}
h1 { font-size: 1.9rem; margin: 0 0 .2rem; }
h1 .dot { color: #b9a6e8; }
p.sub { margin: 0 0 2.2rem; color: #a89cc9; }
h2 {
  font-size: 1.15rem; text-transform: uppercase; letter-spacing: .12em;
  color: #b9a6e8; border-bottom: 1px solid #34295a; padding-bottom: .4rem;
  margin: 2.6rem 0 1.2rem;
}
.char { margin-bottom: 1.6rem; }
.char h3 { margin: 0 0 .5rem; font-weight: 600; color: #d6cbf0; }
.row { display: flex; flex-wrap: wrap; gap: 10px; }
figure {
  margin: 0; padding: 8px 8px 4px; background: #221a3d;
  border: 1px solid #34295a; border-radius: 10px; text-align: center;
}
figure img { display: block; image-rendering: pixelated; }
figure.sprite img { width: 96px; height: 128px; }
figure.monster img { width: 144px; height: 144px; }
figure.scene img { width: 320px; height: 140px; }
figcaption { font-size: .72rem; color: #9a8dc2; padding-top: 4px; }
.sheets a { color: #cbb8ff; }
footer { margin-top: 3rem; color: #7a6da3; font-size: .8rem; }
"""


def figure(src, cls, caption, w, h, alt):
    return (f'<figure class="{cls}"><img src="arts/{src}" width="{w}" height="{h}" '
            f'alt="{html.escape(alt)}" loading="lazy">'
            f'<figcaption>{html.escape(caption)}</figcaption></figure>')


def main():
    os.makedirs(OUT, exist_ok=True)
    arts = os.path.join(OUT, "arts")
    if os.path.isdir(arts):
        shutil.rmtree(arts)
    os.makedirs(arts)
    for name in os.listdir(ASSETS):
        if name.endswith(".png"):
            shutil.copy2(os.path.join(ASSETS, name), arts)

    parts = [
        "<!doctype html><html lang=\"en\"><head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        "<title>Vaiwu - Art Gallery</title>",
        f"<style>{CSS}</style></head><body>",
        "<h1>Vaiwu<span class=\"dot\">.</span> Art Gallery</h1>",
        '<p class="sub">Sprites, monsters and scenes from the Vaiwu tamagotchi '
        "firmware, generated by <code>tools/gen_sprites.py</code>.</p>",
        "<h2>Characters &times; emotions</h2>",
    ]
    for char, title in CHAR_TITLES.items():
        parts.append(f'<div class="char"><h3>{html.escape(title)}</h3><div class="row">')
        for emo in EMOTIONS:
            src = f"sprite_{char}_{emo}.png"
            parts.append(figure(src, "sprite", emo, 96, 128, f"{char} {emo}"))
        parts.append("</div></div>")
    parts.append("<h2>Battle monsters</h2><div class=\"row\">")
    for kind in MONSTERS:
        parts.append(figure(f"monster_{kind}.png", "monster", kind, 96, 96, f"{kind} monster"))
    parts.append("</div><h2>Home interior (time of day)</h2><div class=\"row\">")
    for phase in BG_PHASES:
        parts.append(figure(f"home_{phase}.png", "scene", phase, 320, 140, f"home {phase}"))
    parts.append("</div><h2>Meadow backdrops</h2><div class=\"row\">")
    for phase in BG_PHASES:
        parts.append(figure(f"bg_{phase}.png", "scene", phase, 320, 140, f"meadow {phase}"))
    parts.append("</div><h2>Contact sheets</h2><div class=\"row sheets\">")
    for sheet, label in (("sprites_preview.png", "all sprites"),
                         ("monsters_preview.png", "monsters"),
                         ("home_preview.png", "home interiors"),
                         ("bg_preview.png", "meadow backdrops")):
        parts.append(f'<a href="arts/{sheet}">{label}</a>')
    parts.append("</div><footer>Generated by tools/gen_site.py - vaiwu project</footer>")
    parts.append("</body></html>")

    with open(os.path.join(OUT, "index.html"), "w") as f:
        f.write("\n".join(parts))
    print(f"site built in {OUT}")


if __name__ == "__main__":
    main()

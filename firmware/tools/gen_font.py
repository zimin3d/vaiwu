#!/usr/bin/env python3
"""Generate LVGL 9 fmt_txt fonts with ASCII + Cyrillic from DejaVuSans.

Emits components/ui/src/fonts/vaiwu_font_<size>.c and vaiwu_fonts.h.
Format mirrors LVGL's own lv_font_montserrat_*.c files: 4 bpp, plain
(uncompressed), continuous nibble stream, two FORMAT0_TINY cmaps
(0x20-0x7E and 0x401-0x451), no kerning.

Run from the project root:  python3 tools/gen_font.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

SIZES = [12, 14, 16, 20, 24]
TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
ASCII = list(range(0x20, 0x7F))            # 95 glyphs
CYR = list(range(0x401, 0x452))            # Ё .. ё (81 codepoints)
PAD = 8


def render_glyph(font, cp, ascent, descent):
    ch = chr(cp)
    adv = font.getlength(ch)
    w = int(adv) + 2 * PAD + 8
    h = ascent + descent + 2 * PAD
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((PAD, PAD), ch, font=font, fill=255)
    bbox = img.getbbox()
    if bbox is None:  # blank glyph (space)
        return bytes(), 0, 0, 0, 0, adv
    l, t, r, b = bbox
    box_w, box_h = r - l, b - t
    ofs_x = l - PAD
    ofs_y = (PAD + ascent) - b  # from baseline up to bbox bottom
    crop = img.crop(bbox)
    px = list(crop.getdata())
    # continuous 4bpp nibble stream, row-major, high nibble first
    data = bytearray()
    acc = 0
    nib = 0
    for v in px:
        q = v >> 4
        if nib == 0:
            acc = q << 4
            nib = 1
        else:
            data.append(acc | q)
            nib = 0
    if nib:
        data.append(acc)
    return bytes(data), box_w, box_h, ofs_x, ofs_y, adv


def gen_size(size, out_dir):
    font = ImageFont.truetype(TTF, size)
    ascent, descent = font.getmetrics()
    cps = ASCII + CYR

    bitmaps = []
    dscs = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id 0 reserved */"]
    index = 0
    for cp in cps:
        data, bw, bh, ox, oy, adv = render_glyph(font, cp, ascent, descent)
        bitmaps.append((cp, data))
        dscs.append(
            f"    {{.bitmap_index = {index}, .adv_w = {round(adv * 16)}, "
            f".box_w = {bw}, .box_h = {bh}, .ofs_x = {ox}, .ofs_y = {oy}}}")
        index += len(data)

    name = f"vaiwu_font_{size}"
    path = os.path.join(out_dir, name + ".c")
    with open(path, "w") as f:
        f.write(f"/* Auto-generated by tools/gen_font.py from DejaVuSans, {size}px, 4bpp.\n")
        f.write(" * ASCII 0x20-0x7E + Cyrillic 0x401-0x451. Do not edit by hand. */\n")
        f.write('#include "lvgl.h"\n\n')
        f.write("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {\n")
        for cp, data in bitmaps:
            f.write(f"    /* U+{cp:04X} */\n")
            if data:
                for i in range(0, len(data), 16):
                    f.write("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",\n")
            f.write("\n")
        f.write("};\n\n")
        f.write("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n")
        f.write(",\n".join(dscs))
        f.write("\n};\n\n")
        f.write("static const lv_font_fmt_txt_cmap_t cmaps[] = {\n")
        f.write("    {.range_start = 32, .range_length = 95, .glyph_id_start = 1,\n")
        f.write("     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,\n")
        f.write("     .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},\n")
        f.write("    {.range_start = 0x401, .range_length = 81, .glyph_id_start = 96,\n")
        f.write("     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,\n")
        f.write("     .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},\n")
        f.write("};\n\n")
        f.write("static const lv_font_fmt_txt_dsc_t font_dsc = {\n")
        f.write("    .glyph_bitmap = glyph_bitmap,\n")
        f.write("    .glyph_dsc = glyph_dsc,\n")
        f.write("    .cmaps = cmaps,\n")
        f.write("    .kern_dsc = NULL,\n")
        f.write("    .kern_scale = 0,\n")
        f.write("    .cmap_num = 2,\n")
        f.write("    .bpp = 4,\n")
        f.write("    .kern_classes = 0,\n")
        f.write("    .bitmap_format = 0,\n")
        f.write("};\n\n")
        f.write(f"const lv_font_t {name} = {{\n")
        f.write("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,\n")
        f.write("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,\n")
        f.write(f"    .line_height = {ascent + descent},\n")
        f.write(f"    .base_line = {descent},\n")
        f.write("    .subpx = LV_FONT_SUBPX_NONE,\n")
        f.write("    .underline_position = -1,\n")
        f.write("    .underline_thickness = 1,\n")
        f.write("    .dsc = &font_dsc,\n")
        f.write(f"    .fallback = &lv_font_montserrat_{size},\n")
        f.write("};\n")
    return name


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_dir = os.path.join(root, "components/ui/src/fonts")
    os.makedirs(out_dir, exist_ok=True)
    names = [gen_size(s, out_dir) for s in SIZES]

    with open(os.path.join(root, "components/ui/include/vaiwu/ui/vaiwu_fonts.h"), "w") as h:
        h.write("/* Auto-generated by tools/gen_font.py - do not edit by hand. */\n")
        h.write("#pragma once\n\n#include \"lvgl.h\"\n\n")
        h.write("#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n")
        for n in names:
            h.write(f"extern const lv_font_t {n};\n")
        h.write("\n#ifdef __cplusplus\n}\n#endif\n")
    print("generated fonts:", ", ".join(names))


if __name__ == "__main__":
    main()
